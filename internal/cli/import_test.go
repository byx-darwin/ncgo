func TestDetectIDLPath(t *testing.T) {
	t.Run("prioritizes idl/app/<name>.proto", func(t *testing.T) {
		dir := t.TempDir()
		os.MkdirAll(filepath.Join(dir, "idl", "app"), 0o755)
		os.WriteFile(filepath.Join(dir, "idl", "app", "user-api.proto"), []byte("syntax = \"proto3\";\n"), 0o644)
		os.WriteFile(filepath.Join(dir, "idl", "other.thrift"), []byte("namespace go other\n"), 0o644)
		got := detectIDLPath(dir, "user-api")
		if got != "idl/app/user-api.proto" {
			t.Fatalf("detectIDLPath() = %q, want %q", got, "idl/app/user-api.proto")
		}
	})

	t.Run("scans idl/ directory when no service name", func(t *testing.T) {
		dir := t.TempDir()
		os.MkdirAll(filepath.Join(dir, "idl"), 0o755)
		os.WriteFile(filepath.Join(dir, "idl", "random.thrift"), []byte("namespace go r\n"), 0o644)
		got := detectIDLPath(dir, "")
		if got != "idl/random.thrift" {
			t.Fatalf("detectIDLPath() = %q, want %q", got, "idl/random.thrift")
		}
	})

	t.Run("returns empty when no IDL directory exists", func(t *testing.T) {
		dir := t.TempDir()
		got := detectIDLPath(dir, "nobody")
		if got != "" {
			t.Fatalf("detectIDLPath() = %q, want empty", got)
		}
	})
}

