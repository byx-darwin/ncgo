func TestImportDryRun(t *testing.T) {
	dir := t.TempDir()
	os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module github.com/test/myapp\n\ngo 1.25\n"), 0o644)
	os.WriteFile(filepath.Join(dir, "router.go"), []byte("// Code generated by hz. DO NOT EDIT.\npackage main\n"), 0o644)

	var out bytes.Buffer
	cmd := &cobra.Command{}
	cmd.SetOut(&out)

	opts := &importOptions{Root: dir, DryRun: true}
	err := runImport(opts)(cmd, nil)
	if err != nil {
		t.Fatalf("runImport dry-run: %v", err)
	}

	output := out.String()
	if !strings.Contains(output, "Preview of generated manifest") {
		t.Fatalf("dry-run output missing preview header:\n%s", output)
	}
	if !strings.Contains(output, "github.com/test/myapp") {
		t.Fatalf("dry-run output missing module path:\n%s", output)
	}
	if !strings.Contains(output, "kind: hertz") {
		t.Fatalf("dry-run output missing kind:\n%s", output)
	}

	// Verify no manifest was written.
	if _, err := os.Stat(manifest.Path(dir)); !os.IsNotExist(err) {
		t.Fatalf("dry-run should not write manifest, but found one at %s", manifest.Path(dir))
	}
}

