func TestImportFullWrite(t *testing.T) {
	dir := t.TempDir()
	os.WriteFile(filepath.Join(dir, "go.mod"), []byte("module github.com/test/myapp\n\ngo 1.25\n"), 0o644)
	os.WriteFile(filepath.Join(dir, "handler.go"), []byte("// Code generated by kitex. DO NOT EDIT.\npackage main\n\nfunc main() {\n    svr := userservice.NewServer(new(UserServiceImpl))\n}\n"), 0o644)

	var out bytes.Buffer
	cmd := &cobra.Command{}
	cmd.SetOut(&out)

	opts := &importOptions{Root: dir}
	err := runImport(opts)(cmd, nil)
	if err != nil {
		t.Fatalf("runImport: %v", err)
	}

	output := out.String()
	if !strings.Contains(output, "Created .ncgo/manifest.yaml") {
		t.Fatalf("output missing success message:\n%s", output)
	}
	if !strings.Contains(output, "ncgo doctor") {
		t.Fatalf("output missing next steps:\n%s", output)
	}

	// Load and validate the written manifest.
	m, err := manifest.Load(dir)
	if err != nil {
		t.Fatalf("manifest.Load(): %v", err)
	}
	if m.Module != "github.com/test/myapp" {
		t.Fatalf("manifest.Module = %q, want %q", m.Module, "github.com/test/myapp")
	}
	if m.Service.Kind != manifest.KindKitex {
		t.Fatalf("manifest.Service.Kind = %q, want %q", m.Service.Kind, manifest.KindKitex)
	}
	if m.Mode != manifest.ModeMono {
		t.Fatalf("manifest.Mode = %q, want %q", m.Mode, manifest.ModeMono)
	}
	if m.Service.Name != "userservice" {
		t.Fatalf("manifest.Service.Name = %q, want %q", m.Service.Name, "userservice")
	}
	if m.Service.WithDatabase {
		t.Fatal("manifest.Service.WithDatabase should be false")
	}
}

