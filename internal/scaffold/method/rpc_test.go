func TestAddRPCRejectsServiceMismatch(t *testing.T) {
	root := seedRPCProject(t, manifest.KindKitex,
		"internal/handler/demo/handler.go", kitexHandlerFixture, minimalUsecaseGo)
	_, err := AddRPC(RPCOptions{Root: root, Service: "other", RPC: "Ping"})
	if err == nil || !strings.Contains(err.Error(), "does not match manifest service") {
		t.Fatalf("err = %v, want service mismatch error", err)
	}
}

